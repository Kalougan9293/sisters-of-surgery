export function filterPrices(opts: {
  interventionSlug?: string;
  country?: string;
  city?: string;
}) {
  return prices.filter((p) => {
    if (opts.interventionSlug && p.interventionSlug !== opts.interventionSlug)
      return false;
    if (opts.country && p.country !== opts.country) return false;
    if (opts.city && p.city !== opts.city) return false;
    return true;
  });
}
